/** トップページの「アップデート内容」1件 */
export interface Update {
  /**
   * 一意なID。既読判定は文字列の大小比較(u.id > seen)で行うので、
   * 必ず単調増加させること。日付 + 同日連番の "2026-09-01a" 形式にしておくと
   * 手で書いても順序を間違えにくい。
   */
  id: string;
  /** 表示用の日付 */
  date: string;
  /** 1行見出し */
  title: string;
  /** 箇条書きの詳細(省略可) */
  items?: string[];
}

// 新しいものが先頭。追加するときは必ず配列の先頭に足すこと。
export const UPDATES: Update[] = [
  {
    id: "2026-09-01a",
    date: "2026-09-01",
    title: "エディターの操作性を改善",
    items: [
      "コード欄の外にカーソルがあってもCtrl+Enterで実行できるように",
      "HomeとCmd+←が行の最初の文字へ移動するように(もう一度押すと行頭)",
      "!= や == が ≠ ⩵ に化けていたのを修正",
      "日本語入力の変換をEnterで確定したときに改行が入らないように",
    ],
  },
  {
    id: "2026-08-05a",
    date: "2026-08-05",
    title: "スマホ表示とアプリアイコンを改善",
    items: [
      "ホーム画面に追加したときのアイコンを用意",
      "スマホでヘッダーのメニューが崩れていたのを修正",
      "ランキング表が画面からはみ出して横にずれるのを修正",
    ],
  },
];

// IDが降順(先頭が最新)でないと既読判定が壊れ、バナーが二度と出なくなる。
// 壊れても誰も気づかないので、開発時だけ検査する。
if (import.meta.env.DEV) {
  for (let i = 1; i < UPDATES.length; i++) {
    if (UPDATES[i - 1].id <= UPDATES[i].id) {
      console.warn(
        `[updates] IDが降順になっていません: ${UPDATES[i - 1].id} <= ${UPDATES[i].id}`,
      );
    }
  }
}
